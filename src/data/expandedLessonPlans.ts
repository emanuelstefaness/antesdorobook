import type { LessonPlan, PlanLevel, ClassSize } from "./lessonPlans";
import type { AgeBand, Duration, Material } from "./types";

type PlanoExtra = {
  id: string;
  title: string;
  theme: string;
  objective: string;
  duration: Duration;
  ageBands: AgeBand[];
  classSize: ClassSize;
  level: PlanLevel;
  concepts: string[];
  materials: Material[];
  question: string;
  explain: string;
  investigate: string;
  build: string;
  test: string;
  commonError: string;
  projectId: string;
};

function plano(p: PlanoExtra): LessonPlan {
  const needsComputer = p.materials.includes("computador");
  const needsMicrobit = p.materials.includes("microbit");
  const needsBoard = p.materials.includes("tabuleiro");
  return {
    ...p,
    needsComputer,
    needsMicrobit,
    needsBoard,
    preparation: [
      `Teste previamente a atividade completa e deixe o resultado final pronto para mostrar na abertura.`,
      needsMicrobit
        ? "Confira cabo de dados, pilhas e versão das placas. Deixe o MakeCode aberto e o simulador disponível para quem aguarda a placa."
        : "Separe os materiais em kits por grupo e guarde uma unidade para demonstrar sem desmontar o trabalho dos alunos.",
      `Escreva no quadro o objetivo da aula e reserve os dez minutos finais para teste, correção e compartilhamento.`,
    ],
    intro: `Mostre o resultado final sem explicar como foi feito. Diga que a missão da turma será reconstruir a lógica por trás dele.`,
    triggerQuestion: p.question,
    explanation: p.explain,
    investigation: p.investigate,
    construction: p.build,
    test: p.test,
    debug: `Quando algo não funcionar, não refaça tudo. Peça ao grupo que identifique entrada, decisão e saída e localize o primeiro ponto em que o resultado deixou de ser o esperado. Erro provável: ${p.commonError}`,
    sharing: `Cada grupo apresenta o que produziu, mostra uma tentativa que falhou e explica qual mudança fez o projeto funcionar.`,
    assessment: [
      "O grupo consegue explicar a lógica do projeto sem apenas ler os blocos ou comandos",
      "Testa uma parte por vez e registra ao menos uma correção realizada",
      "Relaciona o resultado ao conceito principal da aula e propõe uma melhoria possível",
    ],
    continuity: { label: "Ver todas as aulas com roteiro completo", href: "/planejar" },
    relatedContent: p.concepts.slice(0, 2).map((id) => ({
      label: `Rever conceito: ${id.replaceAll("-", " ")}`,
      href: `/aprender/${id}`,
    })),
    image: null,
  };
}

